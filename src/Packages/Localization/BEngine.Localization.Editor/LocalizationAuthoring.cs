using System.Text;
using BEngine.Editor;

namespace BEngine.Localization.Editor;

public static class LocalizationAuthoring
{
    public static void ApplyTranslations(LocalizationTable target, LocalizationTable incoming)
    {
        EnsureCanWrite(target);
        target.Validate(); incoming.Validate();
        if (!LocalizationContext.NormalizeLanguage(target.language).Equals(
                LocalizationContext.NormalizeLanguage(incoming.language), StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException("Translation languages do not match.");
        var entries = target.entries.Select(e => new LocalizationEntry { key = e.key, text = e.text, asset = e.asset, comment = e.comment }).ToList();
        var byKey = entries.ToDictionary(entry => entry.key, StringComparer.Ordinal);
        foreach (var entry in incoming.entries)
        {
            var existing = byKey.GetValueOrDefault(entry.key);
            if (existing is null) entries.Add(new LocalizationEntry { key = entry.key, text = entry.text, asset = entry.asset, comment = entry.comment });
            else { existing.text = entry.text; existing.comment = entry.comment; if (entry.asset is not null) existing.asset = entry.asset; }
        }
        Undo.RecordObject(target, "Import Localization");
        target.entries = entries;
        EditorUtility.SetDirty(target);
    }

    public static string GenerateKeys(IEnumerable<LocalizationTable> tables, string className = "LocalizationKeys")
    {
        if (!IsIdentifier(className)) throw new ArgumentException("Invalid C# class name.", nameof(className));
        var output = new StringBuilder("// Generated by BEngine Localization.\npublic static class @").Append(className).Append("\n{\n");
        var names = new HashSet<string>(StringComparer.Ordinal);
        var keys = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var table in tables) { table.Validate(); foreach (var entry in table.entries) keys.Add(entry.key); }
        foreach (var key in keys)
        {
            var identifier = new string(key.Select(ch => char.IsAsciiLetterOrDigit(ch) || ch == '_' ? ch : '_').ToArray());
            if (identifier.Length == 0 || char.IsDigit(identifier[0])) identifier = "_" + identifier;
            if (identifier == className) identifier += "_Key";
            if (!names.Add(identifier)) throw new InvalidDataException($"Generated identifier collision: '{identifier}'. Rename the conflicting keys.");
            output.Append("    public const string @").Append(identifier).Append(" = \"").Append(Escape(key)).Append("\";\n");
        }
        return output.Append("}\n").ToString();
    }

    public static IReadOnlyList<string> FindMissingKeys(IEnumerable<LocalizationTable> tables)
    {
        var groups = tables.GroupBy(t => LocalizationContext.NormalizeLanguage(t.language), StringComparer.OrdinalIgnoreCase)
            .ToDictionary(g => g.Key, g => g.SelectMany(t => t.entries).Select(e => e.key).ToHashSet(StringComparer.Ordinal));
        var keys = groups.Values.SelectMany(v => v).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
        return groups.SelectMany(g => keys.Where(key => !g.Value.Contains(key)).Select(key => $"{g.Key}: {key}")).ToArray();
    }

    /// <summary>Reports malformed formats and differences in arguments across translations of each key.</summary>
    public static IReadOnlyList<string> FindFormatIssues(IEnumerable<LocalizationTable> tables)
    {
        var issues = new List<string>();
        var baseline = new Dictionary<string, (string Language, IReadOnlyList<string> Names)>(StringComparer.Ordinal);
        foreach (var table in tables)
        {
            table.Validate();
            foreach (var entry in table.entries)
            {
                if (entry.text is null) continue;
                IReadOnlyList<string> names;
                try { names = LocalizedTextFormatter.GetArgumentNames(entry.text); }
                catch (FormatException error) { issues.Add($"{table.language}: {entry.key}: {error.Message}"); continue; }
                if (!baseline.TryGetValue(entry.key, out var expected)) baseline[entry.key] = (table.language, names);
                else if (!names.SequenceEqual(expected.Names))
                    issues.Add($"{table.language}: {entry.key}: arguments [{string.Join(", ", names)}] differ from {expected.Language} [{string.Join(", ", expected.Names)}].");
            }
        }
        return issues;
    }

    internal static void EnsureCanWrite(LocalizationTable? target = null)
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode)
            throw new InvalidOperationException("Localization authoring is unavailable in Play Mode.");
        target?.EnsureCanEdit();
    }
    private static bool IsIdentifier(string value) => !string.IsNullOrWhiteSpace(value) &&
        (char.IsAsciiLetter(value[0]) || value[0] == '_') && value.All(ch => char.IsAsciiLetterOrDigit(ch) || ch == '_');
    private static string Escape(string value)
    {
        var result = new StringBuilder();
        foreach (var ch in value)
            if (ch == '"') result.Append("\\\"");
            else if (ch == '\\') result.Append("\\\\");
            else if (char.IsControl(ch) || ch is '\u2028' or '\u2029') result.Append("\\u").Append(((int)ch).ToString("x4"));
            else result.Append(ch);
        return result.ToString();
    }
}
