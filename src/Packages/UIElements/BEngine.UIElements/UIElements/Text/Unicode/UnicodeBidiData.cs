    internal static Directionality Direction(int codepoint)
    {
        var low = 0; var high = Ranges.Length / 3 - 1;
        while (low <= high)
        {
            var middle = (low + high) / 2; var index = middle * 3;
            if (codepoint < Ranges[index]) high = middle - 1;
            else if (codepoint > Ranges[index + 1]) low = middle + 1;
            else return (Directionality)Ranges[index + 2];
        }
        return Directionality.L;
    }
