using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Xml.Linq;
using BEngine.ProjectSystem;
using BEngine.ProjectSystem.Editor;

namespace BEngine.IDE.Editor;

/// <summary>Writes a code-authoring solution. These projects never replace the engine's compilation pipeline.</summary>
public static class IdeSolutionGenerator
{
    private const string OwnerMarker = "# Generated by BEngine IDE Integration";
    internal static readonly JsonSerializerOptions Json = new() { PropertyNamingPolicy = JsonNamingPolicy.CamelCase, WriteIndented = true };

    public static string Generate(ProjectWorkspace workspace) => Generate(workspace, ProjectCodeModel.Capture(workspace));

    public static string Generate(ProjectWorkspace workspace, IReadOnlyList<ProjectCodeAssembly> assemblies)
    {
        ArgumentNullException.ThrowIfNull(workspace);
        ArgumentNullException.ThrowIfNull(assemblies);
        var directory = Path.Combine(workspace.LibraryPath, "IDE");
        var solution = Path.Combine(workspace.RootPath, "BEngine.Project.sln");
        if (File.Exists(solution) && !File.ReadAllText(solution).Contains(OwnerMarker, StringComparison.Ordinal))
            throw new IOException("BEngine.Project.sln already exists and is not an IDE Integration generated file.");
        Directory.CreateDirectory(directory);
        WriteIfChanged(Path.Combine(directory, "Directory.Build.props"), "<Project><PropertyGroup><BaseIntermediateOutputPath>$(MSBuildThisFileDirectory)Build/obj/$(MSBuildProjectName)/</BaseIntermediateOutputPath><BaseOutputPath>$(MSBuildThisFileDirectory)Build/bin/$(MSBuildProjectName)/</BaseOutputPath></PropertyGroup></Project>\n");
        WriteIfChanged(Path.Combine(directory, "Directory.Build.targets"), "<Project />\n");
        foreach (var assembly in assemblies) WriteProject(workspace, directory, assembly);
        var text = new StringBuilder("Microsoft Visual Studio Solution File, Format Version 12.00\n")
            .AppendLine(OwnerMarker).AppendLine("# Visual Studio Version 17")
            .AppendLine("VisualStudioVersion = 17.0.31903.59")
            .AppendLine("MinimumVisualStudioVersion = 10.0.40219.1");
        foreach (var assembly in assemblies)
            text.Append("Project(\"{FAE04EC0-301F-11D3-BF4B-00C04F79EFBC}\") = \"")
                .Append(assembly.Name).Append("\", \"Library\\IDE\\").Append(assembly.Name)
                .Append(".csproj\", \"").Append(Id(assembly.Name)).AppendLine("\"\nEndProject");
        text.AppendLine("Global\n\tGlobalSection(SolutionConfigurationPlatforms) = preSolution\n\t\tDebug|Any CPU = Debug|Any CPU\n\t\tRelease|Any CPU = Release|Any CPU\n\tEndGlobalSection\n\tGlobalSection(ProjectConfigurationPlatforms) = postSolution");
        foreach (var assembly in assemblies)
            foreach (var configuration in new[] { "Debug", "Release" })
            {
                var prefix = $"\t\t{Id(assembly.Name)}.{configuration}|Any CPU";
                text.AppendLine($"{prefix}.ActiveCfg = {configuration}|Any CPU");
                text.AppendLine($"{prefix}.Build.0 = {configuration}|Any CPU");
            }
        text.AppendLine("\tEndGlobalSection\nEndGlobal");
        WriteIfChanged(solution, text.ToString());
        AtomicWrite(Path.Combine(directory, "project.json"), JsonSerializer.Serialize(new { SchemaVersion = 1, ProjectPath = workspace.RootPath, ProjectName = workspace.Project.Name, SolutionPath = solution, EngineVersion = EngineVersion.Current, EnginePath = AppContext.BaseDirectory, GeneratedFiles = Gather3613(assemblies) }, Json));
        [global::BEngine.SkipLoopGuard]
        string[] Gather3613(global::System.Collections.Generic.IEnumerable<global::BEngine.ProjectSystem.Editor.ProjectCodeAssembly> items3613)
        {
            ArgumentNullException.ThrowIfNull(items3613, "source");
            string Evaluate3613(global::BEngine.ProjectSystem.Editor.ProjectCodeAssembly assembly) => assembly.Name + ".csproj";
            global::System.ReadOnlySpan<global::BEngine.ProjectSystem.Editor.ProjectCodeAssembly> values;
            if (items3613.GetType() == typeof(global::BEngine.ProjectSystem.Editor.ProjectCodeAssembly[]))
                values = (global::BEngine.ProjectSystem.Editor.ProjectCodeAssembly[])items3613;
            else if (items3613.GetType() == typeof(global::System.Collections.Generic.List<global::BEngine.ProjectSystem.Editor.ProjectCodeAssembly>))
                values = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan((global::System.Collections.Generic.List<global::BEngine.ProjectSystem.Editor.ProjectCodeAssembly>)items3613);
            else
            {
                return global::System.Linq.Enumerable.ToArray(global::System.Linq.Enumerable.Select(items3613, Evaluate3613));
            }

            if (values.IsEmpty)
                return global::System.Array.Empty<string>();
            var result = new string[values.Length];
            for (var index = 0; index < values.Length; index++)
                result[index] = Evaluate3613(values[index]);
            return result;
        }
        return solution;
    }

    private static void WriteProject(ProjectWorkspace workspace, string directory, ProjectCodeAssembly assembly)
    {
        if (assembly.Name.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 || assembly.Name is "." or "..")
            throw new InvalidDataException("Invalid IDE assembly name.");
        var properties = new XElement("PropertyGroup",
            new XElement("TargetFramework", assembly.TargetFramework), new XElement("LangVersion", "14.0"),
            new XElement("Nullable", "enable"), new XElement("ImplicitUsings", "enable"),
            new XElement("AssemblyName", assembly.Name), new XElement("RootNamespace", assembly.RootNamespace),
            new XElement("EnableDefaultCompileItems", "false"), new XElement("AllowUnsafeBlocks", assembly.AllowUnsafeCode),
            new XElement("DefineConstants", string.Join(';', assembly.DefineSymbols)),
            new XElement("DebugType", "portable"), new XElement("Optimize", "false"),
            new XElement("NuGetAudit", "false"), new XElement("RestoreIgnoreFailedSources", "true"));
        var sources = new XElement("ItemGroup", assembly.SourcePaths.Select(path => new XElement("Compile",
            new XAttribute("Include", path), new XElement("Link", Path.GetRelativePath(workspace.RootPath, path)))));
        var references = new XElement("ItemGroup", assembly.AssemblyReferences.OrderBy(pair => pair.Key, StringComparer.Ordinal)
            .Select(pair => new XElement("Reference", new XAttribute("Include", pair.Key),
                new XElement("HintPath", pair.Value), new XElement("Private", "false"))));
        var projects = new XElement("ItemGroup", assembly.ProjectReferences.Select(name => new XElement("ProjectReference",
            new XAttribute("Include", name + ".csproj"))));
        var packages = new XElement("ItemGroup", assembly.PackageReferences.Select(reference => new XElement("PackageReference",
            new XAttribute("Include", reference.Id), new XAttribute("Version", reference.Version))));
        WriteIfChanged(Path.Combine(directory, assembly.Name + ".csproj"),
            new XDocument(new XElement("Project", new XAttribute("Sdk", "Microsoft.NET.Sdk"), properties, sources, references, projects, packages)).ToString());
    }

    private static string Id(string name) => "{" + new Guid(SHA256.HashData(Encoding.UTF8.GetBytes("BEngine.IDE:" + name)).AsSpan(0, 16)).ToString().ToUpperInvariant() + "}";

    internal static void WriteIfChanged(string path, string text)
    {
        if (File.Exists(path) && File.ReadAllText(path) == text) return;
        AtomicWrite(path, text);
    }

    internal static void AtomicWrite(string path, string text)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.WriteAllText(temporary, text, new UTF8Encoding(false));
            File.Move(temporary, path, overwrite: true);
        }
        finally { if (File.Exists(temporary)) File.Delete(temporary); }
    }
}
