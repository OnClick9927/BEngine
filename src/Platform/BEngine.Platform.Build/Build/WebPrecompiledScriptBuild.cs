using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Xml.Linq;

namespace BEngine.Editor;

/// <summary>Freezes the exact runtime script images for optional Web AOT compilation.</summary>
internal static class WebPrecompiledScriptBuild
{
    private static readonly HashSet<string> ProtectedPublishProperties = new(StringComparer.OrdinalIgnoreCase)
    {
        "BEngineGenerateWasmAotProfile", "WasmAotProfilePath", "WasmStripILAfterAOT",
        "AOTMode", "WasmDedup", "_ExtraTrimmerArgs", "RunAOTCompilation"
    };

    internal static bool IsProtectedPublishProperty(string name) => ProtectedPublishProperties.Contains(name);

    internal static string Write(PlayerBuildContext context, string artifactsDirectory)
    {
        var root = Path.Combine(artifactsDirectory, "precompiled-scripts");
        Directory.CreateDirectory(root);
        var nativePaths = context.WebPrecompiledManagedCodeAssemblyPaths
            .Select(Path.GetFullPath).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var sharedPaths = context.WebPrecompiledSharedManagedCodeAssemblyPaths
            .Select(Path.GetFullPath).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var images = new List<Image>();
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var source in context.WebPrecompiledManagedCodeReferencePaths.Concat(context.WebPrecompiledManagedCodeAssemblyPaths)
                     .Concat(context.WebPrecompiledSharedManagedCodeAssemblyPaths)
                     .Select(Path.GetFullPath).Distinct(StringComparer.OrdinalIgnoreCase).Order(StringComparer.Ordinal))
        {
            var bytes = File.ReadAllBytes(source);
            using var stream = new MemoryStream(bytes, writable: false);
            using var pe = new PEReader(stream);
            if (!pe.HasMetadata)
                throw new InvalidDataException($"Web script reference '{source}' has no managed metadata.");
            var metadata = pe.GetMetadataReader();
            if (!metadata.IsAssembly)
                throw new InvalidDataException($"Web script reference '{source}' is not an assembly.");
            var name = metadata.GetString(metadata.GetAssemblyDefinition().Name);
            if (!Regex.IsMatch(name, "^[A-Za-z_][A-Za-z0-9_.-]*$", RegexOptions.CultureInvariant))
                throw new InvalidDataException($"Web precompiled script assembly name '{name}' is unsupported.");
            if (!name.Equals(Path.GetFileNameWithoutExtension(source), StringComparison.OrdinalIgnoreCase))
                throw new InvalidDataException($"Web script reference filename '{Path.GetFileName(source)}' " +
                    $"does not match its assembly name '{name}'.");
            var mvid = metadata.GetGuid(metadata.GetModuleDefinition().Mvid);
            if (mvid == Guid.Empty)
                throw new InvalidDataException($"Web script reference '{name}' requires a non-empty MVID.");
            if (!names.Add(name))
                throw new InvalidDataException($"Web script reference '{name}' has multiple runtime images.");
            var destination = Path.Combine(root, name + ".dll");
            File.WriteAllBytes(destination, bytes);
            images.Add(new(name, Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant(),
                mvid.ToString(), destination, nativePaths.Contains(source), sharedPaths.Contains(source)));
        }
        var nativeImages = images.Where(static image => image.Native).ToArray();
        if (nativeImages.Length == 0)
            throw new InvalidDataException("Web script precompilation requires runtime managed-code images.");

        var manifestPath = Path.Combine(root, "images.json");
        File.WriteAllText(manifestPath, JsonSerializer.Serialize(images,
            new JsonSerializerOptions { WriteIndented = true }));
        var linkerPath = Path.Combine(root, "copy-images.xml");
        new XDocument(new XElement("linker", images.Select(image => new XElement("assembly",
            new XAttribute("fullname", image.Name), new XAttribute("preserve", "all"),
            new XAttribute("action", "copy"))))).Save(linkerPath);

        var bootstrapPath = Path.Combine(root, "PrecompiledScriptBootstrap.cs");
        var bootstrap = new StringBuilder("// Generated by the BEngine Web build pipeline.\n" +
            "internal static class BEnginePrecompiledScriptBootstrap\n{\n" +
            "    [System.Runtime.CompilerServices.ModuleInitializer]\n" +
            "    [System.Diagnostics.CodeAnalysis.SuppressMessage(\"Usage\", \"CA2255\")]\n" +
            "    internal static void Initialize()\n    {\n");
        foreach (var image in images)
            bootstrap.Append(image.Shared
                    ? "        BEngine.HotUpdate.ManagedCodePrecompiledAssemblies.RegisterShared("
                    : "        BEngine.HotUpdate.ManagedCodePrecompiledAssemblies.Register(")
                .Append(JsonSerializer.Serialize(image.Name)).Append(", ")
                .Append(JsonSerializer.Serialize(image.Sha256)).Append(", ")
                .Append(JsonSerializer.Serialize(image.Mvid)).Append(");\n");
        bootstrap.Append("    }\n}\n");
        File.WriteAllText(bootstrapPath, bootstrap.ToString(), new UTF8Encoding(false));

        // RootMode alone does not preserve the original MVID. The explicit ILLink
        // copy action is required; the profile tool verifies every linked byte
        // against images.json before Mono's native compiler can consume it.
        var properties = new XElement("PropertyGroup",
            new XElement("BEngineWebPrecompiledManifest", manifestPath),
            new XElement("BEngineGenerateWasmAotProfile", "true"),
            new XElement("WasmAotProfilePath", string.Empty),
            new XElement("AOTMode", "LLVMOnlyInterp"),
            new XElement("WasmDedup", "true"),
            // Strip eligible BCL/Host method bodies after native compilation.
            // The target below restores the frozen script images before the
            // SDK fingerprints/bundles them, preserving their AB identity.
            new XElement("WasmStripILAfterAOT", "true"),
            new XElement("_ExtraTrimmerArgs", "$(_ExtraTrimmerArgs)" +
                string.Concat(images.Select(static image => " --action copy " + image.Name))));
        var items = new XElement("ItemGroup",
            images.Select(image => new XElement("Reference", new XAttribute("Include", image.Name),
                new XElement("HintPath", image.AssemblyPath), new XElement("Private", "true"))),
            images.Select(image => new XElement("TrimmerRootAssembly", new XAttribute("Include", image.Name),
                new XAttribute("RootMode", "All"))),
            nativeImages.Select(image => new XElement("BEnginePrecompiledAssembly", new XAttribute("Include", image.Name))),
            images.Where(static image => !image.Native).Select(image =>
                new XElement("BEngineInterpretedScriptAssembly", new XAttribute("Include", image.Name))),
            new XElement("TrimmerRootDescriptor", new XAttribute("Include", linkerPath)),
            new XElement("Compile", new XAttribute("Include", bootstrapPath)));
        // Cold packages are still needed to resolve native scripts' references.
        // Keep their exact original IL/metadata, but never compile them merely
        // because a native game assembly refers to them. Run after the Host's
        // own policy, before the SDK snapshots these items for its AOT inputs.
        var interpretedPolicy = new XElement("Target",
            new XAttribute("Name", "_BEngineConfigureInterpretedScriptReferences"),
            new XAttribute("AfterTargets", "_BEngineConfigureHybridWasmRuntime"),
            new XElement("ItemGroup", images.Select(image => new XElement("WasmAssembliesToBundle",
                new XAttribute("Condition", "'%(WasmAssembliesToBundle.FileName)' == '" + image.Name + "'"),
                new XAttribute("AOT_InternalForceToInterpret", image.Native ? "false" : "true")))));
        var restoreImages = new XElement("Target",
            new XAttribute("Name", "_BEngineRestorePrecompiledScriptImages"),
            new XAttribute("AfterTargets", "_WasmAotCompileApp"),
            new XAttribute("Condition", "'$(RunAOTCompilation)' == 'true' and '$(WasmStripILAfterAOT)' == 'true'"),
            new XElement("ItemGroup", images.Select(image =>
                new XElement("_BEngineFrozenScriptOutput",
                    new XAttribute("Include", "@(_WasmAssembliesInternal->WithMetadataValue('Filename', '" + image.Name + "'))"),
                    new XElement("BEngineFrozenSource", image.AssemblyPath),
                    new XElement("BEngineFrozenSha256", image.Sha256)))),
            new XElement("Error",
                new XAttribute("Condition", "'@(_BEngineFrozenScriptOutput->Count())' != '" + images.Count + "'"),
                new XAttribute("Text", "The Web SDK did not return every frozen script image after AOT compilation.")),
            new XElement("Copy",
                new XAttribute("SourceFiles", "@(_BEngineFrozenScriptOutput->'%(BEngineFrozenSource)')"),
                new XAttribute("DestinationFiles", "@(_BEngineFrozenScriptOutput)")),
            new XElement("GetFileHash",
                new XAttribute("Files", "@(_BEngineFrozenScriptOutput)"),
                new XAttribute("Algorithm", "SHA256"),
                new XElement("Output", new XAttribute("TaskParameter", "Items"),
                    new XAttribute("ItemName", "_BEngineVerifiedFrozenScriptOutput"))),
            new XElement("Error",
                new XAttribute("Condition", "'%(_BEngineVerifiedFrozenScriptOutput.FileHash)' != '%(_BEngineVerifiedFrozenScriptOutput.BEngineFrozenSha256)'"),
                new XAttribute("Text", "Web AOT stripping changed the frozen script image '%(_BEngineVerifiedFrozenScriptOutput.Identity)'.")));
        var propsPath = Path.Combine(root, "scripts.props");
        new XDocument(new XElement("Project", properties, items, interpretedPolicy, restoreImages)).Save(propsPath);
        return propsPath;
    }

    private sealed record Image(string Name, string Sha256, string Mvid, string AssemblyPath, bool Native, bool Shared);
}
