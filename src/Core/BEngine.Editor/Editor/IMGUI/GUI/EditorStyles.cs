    internal static void ApplyAppearance(GUISkin skin, EditorThemePalette palette, int fontSize)
    {
        ArgumentNullException.ThrowIfNull(skin);
        var previous = GUI.skin;
        GUI.skin = skin;
        try
        {
            ApplyAppearance(palette, fontSize);
        }
        finally
        {
            GUI.skin = previous;
        }
    }

