    private static IEnumerable<GUIStyle> AllStyles =>
        GUI.skin.EnumerateBuiltInStyles().Select(static pair => pair.Style);

    private static void ApplyDerivedStyles(EditorThemePalette palette)
    {
        CopyStyle(miniLabel, miniBoldLabel, centeredGreyMiniLabel, wordWrappedMiniLabel, whiteMiniLabel);
        CopyStyle(label, wordWrappedLabel, whiteLabel, whiteBoldLabel, toolbarLabel, inspectorTitlebarText,
            notificationText, assetLabel, assetLabelPartial, assetLabelIcon, progressBarText);
        CopyStyle(largeLabel, whiteLargeLabel);
        centeredGreyMiniLabel.alignment = TextAnchor.MiddleCenter;
        wordWrappedMiniLabel.wordWrap = true;
        wordWrappedLabel.wordWrap = true;
        SetText(whiteLabel, Color.white, palette.DisabledText);
        SetText(whiteMiniLabel, Color.white, palette.DisabledText);
        SetText(whiteLargeLabel, Color.white, palette.DisabledText);
        SetText(whiteBoldLabel, Color.white, palette.DisabledText);

        CopyStyle(textField, boldTextField, miniTextField, objectField, toolbarTextField,
            textFieldDropDownText);
        CopyStyle(popup, layerMaskField, textFieldDropDown, toolbarPopup, toolbarPopupLeft,
            toolbarPopupRight, toolbarDropDown, toolbarDropDownLeft, toolbarDropDownRight,
            toolbarCreateAddNewDropDown, minMaxStateDropdown);
        CopyStyle(GUI.skin.toggle, radioButton, toggleMixed);
        CopyStyle(foldout, titlebarFoldout, foldoutPreDrop, foldoutHeader, foldoutHeaderIcon,
            foldoutSelected);
        CopyStyle(helpBox, toggleGroup, frameBox, tooltip, notificationBackground, dropDownList,
            progressBarBack);
        CopyStyle(colorPickerSwatch, objectFieldThumb, objectFieldMiniThumb, colorPickerBox);
        CopyStyle(dropDownButton, objectFieldButton, optionsButtonStyle, dropDownToggleButton);

        CopyStyle(toolbar, contentToolbar);
        CopyStyle(toolbarButton, toolbarButtonLeft, toolbarButtonRight, toolbarDropDownToggle,
            toolbarDropDownToggleButton, toolbarDropDownToggleRight);
        CopyStyle(toolbarSearchField, toolbarSearchFieldPopup, toolbarSearchFieldWithJumpSynced,
            toolbarSearchFieldWithJumpPopupSynced, toolbarSearchFieldWithJump,
            toolbarSearchFieldWithJumpPopup, searchField);
        CopyStyle(toolbarIconButton, toolbarSearchFieldJumpButton, toolbarSearchFieldCancelButton,
            toolbarSearchFieldCancelButtonEmpty, toolbarSearchFieldCancelButtonWithJump,
            toolbarSearchFieldCancelButtonWithJumpEmpty, searchFieldCancelButton,
            searchFieldCancelButtonEmpty, iconButton);
        CopyStyle(miniButton, miniButtonLeft, miniButtonMid, miniButtonRight, miniPullDown);

        CopyStyle(inspectorDefaultMargins, inspectorHorizontalDefaultMargins, inspectorFullWidthMargins,
            defaultContentMargins, overrideMargin);
        CopyStyle(GUI.skin.window, viewBackground, inspectorBig);
        CopyStyle(inspectorTitlebar, inspectorTitlebarFlat);
        CopyStyle(treeViewRowSelected, selectionRect);
        CopyStyle(GUI.skin.horizontalSlider, toolbarSlider);
        CopyStyle(GUI.skin.horizontalSliderThumb, minMaxHorizontalSliderThumb);
        CopyStyle(GUI.skin.scrollView, scrollViewAlt);
        CopyStyle(colorField, progressBarBar);
    }

    private static void CopyStyle(GUIStyle source, params GUIStyle[] destinations)
    {
        foreach (var destination in destinations)
        {
            var name = destination.name;
            destination.CopyFrom(source);
            destination.name = name;
        }
    }

    private static void ApplyTransparent(GUIStyle style, Color text, Color disabledText)
        => ApplySurface(style, Transparent, Transparent, Transparent, Transparent,
            Transparent, Transparent, text, disabledText, false);

    private static void ApplySurface(GUIStyle style, Color normal, Color hover, Color active,
        Color focused, Color border, Color focusBorder, Color text, Color disabledText,
        bool bordered = true)
    {
        style.borderWidth = bordered ? Fix64.One : Fix64.Zero;
        SetState(style.normal, normal, text, border);
        SetState(style.hover, hover, text, border);
        SetState(style.active, active, text, focusBorder);
        SetState(style.focused, focused, text, focusBorder);
        SetState(style.onNormal, normal, text, border);
        SetState(style.onHover, hover, text, border);
        SetState(style.onActive, active, text, focusBorder);
        SetState(style.onFocused, focused, text, focusBorder);
        SetState(style.disabled, normal, disabledText, border);
    }

    private static void SetText(GUIStyle style, Color text, Color disabledText)
    {
        style.normal.textColor = text;
        style.hover.textColor = text;
        style.active.textColor = text;
        style.focused.textColor = text;
        style.onNormal.textColor = text;
        style.onHover.textColor = text;
        style.onActive.textColor = text;
        style.onFocused.textColor = text;
        style.disabled.textColor = disabledText;
    }

    private static void SetState(GUIStyleState state, Color background, Color text, Color border)
        => (state.backgroundColor, state.textColor, state.borderColor) = (background, text, border);

    private static void SetBackgroundImage(GUIStyle style, Texture? image)
    {
        style.normal.backgroundImage = image;
        style.hover.backgroundImage = image;
        style.active.backgroundImage = image;
        style.focused.backgroundImage = image;
        style.onNormal.backgroundImage = image;
        style.onHover.backgroundImage = image;
        style.onActive.backgroundImage = image;
        style.onFocused.backgroundImage = image;
        style.disabled.backgroundImage = image;
    }

